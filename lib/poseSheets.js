// bitGen Studio — the character-sheet POSE TEMPLATES (2.207.0, Tim: "make
// the character sheet reference black and white line drawings and create new
// ones to articulate the poses for humans, horses, dogs, cats, mice etc").
//
// WHY THEY EXIST: the Klein edit treats its FIRST image slot as "the image
// being edited", so when the uploaded photo rode there the render held onto
// the photo's SHAPES and composition — i2i/lineart-controlnet behaviour, by
// Tim's diagnosis — which is one reason a horse came out a furry, and why
// photo artifacts bled into the sheet. Now a black-line pose template rides
// slot 1 (it IS the sheet being edited: panels + poses) and the photo rides
// slot 2, identity only.
//
// The PNGs live in static/pose-sheets/ and are generated by
// scripts/make_pose_sheets.py (dev-time; they ship prebuilt).
const fs = require("fs");
const path = require("path");

const DIR = path.join(__dirname, "..", "static", "pose-sheets");

// Order matters: text matches are tried top to bottom, so the specific
// species outrank the generic quadruped fallback.
const SHEETS = [
  { id: "human", name: "Human",
    match: /\b(human|person|man|woman|boy|girl|guy|lady)\b/i },
  { id: "horse", name: "Horse",
    match: /\b(horse|pony|mare|stallion|foal|colt|filly|donkey|mule|zebra|unicorn)\b/i },
  { id: "dog", name: "Dog",
    match: /\b(dog|pupp(y|ies)|wolf|wolves|fox|coyote|hound|retriever|shepherd|terrier|spaniel)\b/i },
  { id: "cat", name: "Cat",
    match: /\b(cat|kitten|kitty|lion|tiger|leopard|panther|lynx|cheetah)\b/i },
  { id: "mouse", name: "Mouse",
    match: /\b(mouse|mice|rat|hamster|gerbil|rodent|squirrel|chipmunk)\b/i },
  { id: "quadruped", name: "Quadruped (generic)", match: null },
];

/** Absolute path of a template's PNG, or null when the id is unknown or the
 *  file is missing (a deleted asset must degrade to no-template, not 500). */
function file(id) {
  if (!SHEETS.some((s) => s.id === String(id || ""))) return null;
  const p = path.join(DIR, String(id) + ".png");
  return fs.existsSync(p) ? p : null;
}

/** The templates that exist on disk, registry order — the dialog's rows. */
function list() {
  return SHEETS.filter((s) => file(s.id)).map(({ id, name }) => ({ id, name }));
}

/** Which template fits, from the dialog's kind plus the free text (subject +
 *  description). The KIND is authoritative when given: person is always the
 *  human template (a "cat lady" is a person), animal never is (a mare owned
 *  by a woman is still a horse) — species words then refine within animals,
 *  falling back to the generic quadruped. Vehicles, objects and fully
 *  unknown subjects get NO template (poses are meaningless for a car). */
function guess(kind, text) {
  const k = String(kind || "").toLowerCase();
  if (k === "vehicle" || k === "object") return null;
  if (k === "person") return "human";
  const t = String(text || "");
  for (const s of SHEETS)
    if (s.match && s.match.test(t) && !(k === "animal" && s.id === "human"))
      return s.id;
  if (k === "animal") return "quadruped";
  return null;
}

/** The template ONE sheet render uses: "" (auto) -> guess; "none" -> null;
 *  an explicit id is used as given. Returns { id, name, file } or null. */
function pick(poseId, kind, text) {
  const want = String(poseId || "").trim().toLowerCase();
  const id = want === "none" ? null : (want || guess(kind, text));
  if (!id) return null;
  const f = file(id);
  if (!f) return null;
  const s = SHEETS.find((x) => x.id === id);
  return { id, name: s.name, file: f };
}

module.exports = { DIR, SHEETS, file, list, guess, pick };
